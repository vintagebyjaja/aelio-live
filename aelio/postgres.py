"""PostgreSQL compatibility for the existing engine store (private aelio_engine schema).
SQLite remains an explicitly selected offline test/migration source, never the production default.
"""
import re
import psycopg

class Row(dict):
    def __getitem__(self,key):
        return tuple(self.values())[key] if isinstance(key,int) else super().__getitem__(key)

def row_factory(cursor):
    names=[c.name for c in cursor.description] if cursor.description else []
    return lambda values:Row(zip(names,values))

def sql(statement):
    statement=re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',statement,flags=re.I)
    statement=re.sub(r'\bREAL\b','DOUBLE PRECISION',statement)
    statement=re.sub(r"json_extract\((\w+),'\$\.(\w+)'\)",r"(\1::jsonb->>'\2')",statement)
    if 'SUM((' in statement and "amount_refunded" in statement:
        statement=statement.replace("(receipt::jsonb->>'amount_refunded')","(receipt::jsonb->>'amount_refunded')::numeric")
    statement=statement.replace('BEGIN IMMEDIATE','BEGIN')
    # Bind only placeholders outside quoted SQL strings; literal question marks remain intact.
    result=[];quoted=False;i=0
    while i<len(statement):
        c=statement[i]
        if c=="'":
            result.append(c)
            if quoted and i+1<len(statement) and statement[i+1]=="'":result.append("'");i+=2;continue
            quoted=not quoted
        else:result.append('%s' if c=='?' and not quoted else c)
        i+=1
    return ''.join(result)

class Connection:
    def __init__(self,url):
        self.raw=psycopg.connect(url,autocommit=True,row_factory=row_factory)
        self.raw.execute('SET search_path TO aelio_engine, public')
    def execute(self,s,params=()):
        return self.raw.execute(sql(s),params or None)
    def executescript(self,s):
        s=re.sub(r'--[^\n]*','',s)
        for part in s.split(';'):
            if part.strip():self.execute(part)
    def __enter__(self):
        self.execute('BEGIN');self.execute('SELECT pg_advisory_xact_lock(14873821)');return self
    def __exit__(self,typ,value,tb):
        self.execute('ROLLBACK' if typ else 'COMMIT')
    def close(self):self.raw.close()
